'use strict';
const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('gravityDesktop',{
 info:()=>ipcRenderer.invoke('app:info'),
 listStudies:()=>ipcRenderer.invoke('study:list'),
 loadStudy:id=>ipcRenderer.invoke('study:load',id),
 saveStudy:study=>ipcRenderer.invoke('study:save',study),
 deleteStudy:id=>ipcRenderer.invoke('study:delete',id),
 loadSettings:()=>ipcRenderer.invoke('settings:load'),
 saveSettings:value=>ipcRenderer.invoke('settings:save',value),
 exportStudy:study=>ipcRenderer.invoke('study:export-json',study),
 importStudy:()=>ipcRenderer.invoke('study:import-json'),
 saveEvidencePackage:pkg=>ipcRenderer.invoke('evidence:save',pkg),
 listEvidencePackages:()=>ipcRenderer.invoke('evidence:list'),
 loadEvidencePackage:id=>ipcRenderer.invoke('evidence:load',id),
 loadLatestEvidencePackage:()=>ipcRenderer.invoke('evidence:latest'),
 deleteEvidencePackage:id=>ipcRenderer.invoke('evidence:delete',id),
 exportEvidencePackage:pkg=>ipcRenderer.invoke('evidence:export',pkg),
 importEvidencePackage:()=>ipcRenderer.invoke('evidence:import'),
 readProcessFile:payload=>ipcRenderer.invoke('process-file:extract',payload),
 requestTts:payload=>ipcRenderer.invoke('tts:request',payload),
 createDeviceLink:snapshot=>ipcRenderer.invoke('device-link:create',snapshot),
 getDeviceLinkSession:()=>ipcRenderer.invoke('device-link:session'),
 getDeviceLinkState:()=>ipcRenderer.invoke('device-link:state'),
 pushDeviceLink:(snapshot,revision)=>ipcRenderer.invoke('device-link:push',{snapshot,revision}),
 acceptDeviceLinkLatest:()=>ipcRenderer.invoke('device-link:accept'),
 endDeviceLink:()=>ipcRenderer.invoke('device-link:end'),
 savePdf:name=>ipcRenderer.invoke('report:pdf',name),
 print:()=>ipcRenderer.invoke('report:print'),
 openDataFolder:()=>ipcRenderer.invoke('system:open-data')
});
