const {test,expect}=require('@playwright/test');
const fs=require('node:fs');

const testSop='QA Fictional Prep Closing Procedure';
const testRestaurant='QA Fictional Inventory Kitchen';
const readInventory=page=>page.evaluate(()=>JSON.parse(localStorage.getItem('gravityInventoryCenter.v1')||'null'));
const readFoundry=page=>page.evaluate(async()=>{const r=await fetch('/api/workroom',{cache:'no-store'});if(!r.ok)throw Error('Workroom GET failed: '+r.status);return (await r.json()).data;});

async function setUpInventory(page){
 await page.goto('/apps/inventory-center/index.html');
 await page.locator('#edit-profile').click();
 await page.locator('#profile-restaurant').fill(testRestaurant);
 await page.locator('#save-profile').click();
 await expect.poll(async()=>(await readInventory(page))?.profile?.restaurant).toBe(testRestaurant);
 await page.locator('button.tab[data-view="locations"]').click();
 await page.locator('#loc-name').fill('QA Walk-in Cooler');
 await page.locator('#loc-order').fill('1');
 await page.locator('#location-form button[type="submit"]').click();
 await expect.poll(async()=>(await readInventory(page))?.locations?.length).toBe(1);
 await page.locator('button.tab[data-view="items"]').click();
 await page.locator('#add-item').click();
 await page.locator('#item-name').fill('QA Chicken Breast');
 await page.locator('#item-category').fill('Protein');
 await page.locator('#item-vendor').fill('QA Supplier');
 await page.locator('#item-sku').fill('QA-CH-001');
 await page.locator('#item-cost').fill('3.5');
 await page.locator('#item-unit').fill('lb');
 await page.locator('#item-onhand').fill('8');
 await page.locator('#save-item').click();
 await expect.poll(async()=>(await readInventory(page))?.items?.length).toBe(1);
 await expect(page.locator('#items-table tbody tr')).toContainText(['QA Chicken Breast']);
}

test('SOP Foundry creates, reopens and revises a draft without publishing it',async({page})=>{
 await page.addInitScript(()=>sessionStorage.setItem('gravityFoundryRoleV15','build'));
 await page.goto('/apps/sop-foundry/workroom.html');
 await expect(page.locator('button[data-view="sops"]')).toBeVisible();
 await expect(page.locator('button[data-action="new-sop"]').first()).toBeVisible({timeout:18000});
 await page.locator('button[data-action="new-sop"]').first().evaluate(x=>x.click());
 const form=page.locator('#editForm');
 await expect(form).toBeVisible();
 await form.locator('[name="title"]').fill(testSop);
 await form.locator('[name="station"]').fill('Prep');
 await form.locator('[name="category"]').fill('Closing');
 await form.locator('[name="role"]').fill('QA Prep Cook');
 await form.locator('[name="purpose"]').fill('Test fictional safe closing process; never publish.');
 await form.locator('[name="steps"]').fill('Review the test setup\nClean fictional prep table');
 await form.locator('[name="changeSummary"]').fill('Initial QA draft');
 await form.locator('[type="submit"]').click();
 await expect(form).toHaveCount(0);
 const snap=await readFoundry(page);
 const first=snap.sops.find(s=>s.title===testSop);
 expect(first).toBeTruthy();
 expect(first.status).toBe('Draft');
 expect(first.revision).toBe('1.0');
 expect(first.steps).toHaveLength(2);
 await page.reload();
 const again=await readFoundry(page);
 expect(again.sops.find(s=>s.id===first.id)?.title).toBe(testSop);
 await page.locator('button[data-view="sops"]').evaluate(x=>x.click());
 await page.locator('#sopSearch').fill(testSop);
 await page.locator('#sopItems [data-sop]').first().evaluate(x=>x.click());
 await page.locator('#sopDetail [data-action="edit-sop"]').first().evaluate(x=>x.click());
 await page.locator('#editForm [name="steps"]').fill('Review the test setup\nClean fictional prep table\nRecord the QA closing check');
 await page.locator('#editForm [name="changeSummary"]').fill('Added QA checklist record step');
 await page.locator('#editForm [type="submit"]').click();
 await expect.poll(async()=>{const d=await readFoundry(page);return d.sops.find(s=>s.id===first.id)?.revision}).toBe('1.1');
 await page.reload();
 const edited=(await readFoundry(page)).sops.find(s=>s.id===first.id);
 expect(edited.steps).toHaveLength(3);
 expect(edited.status).toBe('Draft');
 const publicData=await page.evaluate(async()=>{const r=await fetch('/api/published-sops');return (await r.json()).data.sops;});
 expect(publicData.some(s=>s.id===first.id)).toBe(false);
});

test('Inventory Center saves, reopens and edits a counted item without losing its movement history',async({page})=>{
 await setUpInventory(page);
 const before=await readInventory(page);
 expect(before.movements).toHaveLength(1);
 expect(before.items[0].balances[before.locations[0].id]).toBe(8);
 await page.reload();
 await page.locator('button.tab[data-view="items"]').click();
 await expect(page.locator('#items-table tbody tr')).toContainText(['QA Chicken Breast']);
 await page.locator('#items-table [data-edit-item]').first().click();
 await page.locator('#item-vendor').fill('QA Revised Supplier');
 await page.locator('#save-item').click();
 await expect.poll(async()=>(await readInventory(page)).items[0].vendor).toBe('QA Revised Supplier');
 await page.reload();
 const after=await readInventory(page);
 expect(after.items).toHaveLength(1);
 expect(after.items[0].vendor).toBe('QA Revised Supplier');
 expect(after.items[0].balances[after.locations[0].id]).toBe(8);
 expect(after.movements).toHaveLength(1);
 await page.locator('button.tab[data-view="history"]').click();
 await expect(page.locator('#history-table tbody tr')).toHaveCount(1);
});

test('Inventory Center backup restores a full item and refuses malformed recovery data',async({page})=>{
 await setUpInventory(page);
 const pending=page.waitForEvent('download');
 await page.locator('#backup-json').click();
 const download=await pending, bytes=fs.readFileSync(await download.path());
 const backup=JSON.parse(bytes.toString('utf8'));
 expect(backup.state.items).toHaveLength(1);
 expect(backup.state.movements).toHaveLength(1);
 await page.locator('#items-table [data-edit-item]').first().click();
 await page.locator('#item-vendor').fill('After-backup altered vendor');
 await page.locator('#save-item').click();
 await expect.poll(async()=>(await readInventory(page)).items[0].vendor).toBe('After-backup altered vendor');
 page.on('dialog',d=>d.accept());
 await page.locator('#restore-json').evaluate(el=>el.click());
 await page.locator('#web-restore-input').setInputFiles({name:'qa-inventory.json',mimeType:'application/json',buffer:bytes});
 await expect(page.locator('#app-status')).toContainText('Backup restored successfully');
 const restored=await readInventory(page);
 expect(restored.items[0].vendor).toBe('QA Supplier');
 expect(restored.items[0].balances[restored.locations[0].id]).toBe(8);
 expect(restored.movements).toHaveLength(1);
 await page.reload();
 expect((await readInventory(page)).items[0].vendor).toBe('QA Supplier');
 await page.locator('#restore-json').evaluate(el=>el.click());
 await page.locator('#web-restore-input').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('not-json')});
 await expect(page.locator('#app-status')).not.toContainText('Backup restored successfully');
 expect((await readInventory(page)).items[0].vendor).toBe('QA Supplier');
});
